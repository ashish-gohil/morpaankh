const ctx = {
  orderId: '1234567890',
  token: 'TESTTOKEN16CHARS',
  flowToken: 'ft.exp.sig',
  flowActionData: { first_name: 'Aarav' },
  url: 'https://dry.run/pay',
  imageUrl: 'https://cdn.shopify.com/sample.jpg?width=800&height=800&crop=center',
};

/*
 * Flow W's email is the same offer for somebody WhatsApp cannot reach, so it
 * is rendered here beside the templates: it is copy, it has placeholders, and
 * the only other way to look at it is to send one.
 */
function renderEmail() {
  const vars = {
    customer_name: 'Priya',
    code: 'MORPAANKHPRIYA4729',
    saving: '₹200',
    min_order: '₹1,500',
    expires_at: 'tomorrow at 11:00 AM',
    top_picks: 'Khili Dhoop, Bandhan and Morani',
  };
  const picks = [
    { title: 'Khili Dhoop', handle: 'khili-dhoop', imageUrl: 'https://cdn.shopify.com/sample-a.jpg' },
    { title: 'Bandhan', handle: 'bandhan', imageUrl: 'https://cdn.shopify.com/sample-b.jpg' },
    { title: 'Morani', handle: 'morani', imageUrl: 'https://cdn.shopify.com/sample-c.jpg' },
  ];
  return renderSubscriberEmail({
    vars,
    rawFirstName: 'Priya',
    url: 'https://dry.run/w/TESTTOKEN16CHARS',
    picks,
    unsubscribeUrl: 'https://www.morpaankh.in/unsubscribe?id=sample',
    shopUrl: 'https://www.morpaankh.in',
    utm: 'utm_source=email&utm_medium=automation&utm_campaign=welcome_24h',
    escapeHtml,
  });
}

/*
 * --lang hi : write docs/hindi-copy-review.md, English beside Hindi, and stop.
 *
 * This is gate G1's whole artefact. The owner reads Hindi and this code does
 * not, so every sentence in templates.hi.mjs and session.hi.mjs is a draft
 * until they have seen it next to the English it is supposed to be saying.
 * Rendered with sample values rather than shown as a template, because
 * {{customer_name}} is not what the customer reads.
 */
if (process.argv.includes('--lang') && process.argv[process.argv.indexOf('--lang') + 1] === 'hi') {
  const { writeFileSync, mkdirSync } = await import('node:fs');
  const { TEMPLATES_HI, PLAIN_HI, HI_NOT_SUBMITTED } = await import('../messages/templates.hi.mjs');
  const { SESSION_HI } = await import('../messages/session.hi.mjs');
  const { NO_PRICE } = await import('../messages/templates.mjs');
  const { STR, LANGS } = await import('../messages/lang.mjs');

  const fillBody = (body, ex) => body.replace(/\{\{(\w+)\}\}/g, (_, n) => (ex && ex[n] !== undefined ? ex[n] : sampleValue(n)));
  const out = [];
  const w = (line = '') => out.push(line);

  w('# Hindi copy review');
  w();
  w('Every Hindi message this service can send, beside the English it is saying.');
  w('Rendered with sample values, so this is what a customer actually reads.');
  w();
  w('**What to do with this file.** Read the Hindi. Where it is wrong, stiff, or');
  w('says something the English does not, edit `messages/templates.hi.mjs` or');
  w('`messages/session.hi.mjs` and run `npm run dryrun:render -- --lang hi` again.');
  w('Nothing here has been submitted to Meta yet, so the copy is still free to');
  w('change. Once a template is approved, changing a word means a new version');
  w('name and another review.');
  w();
  w('**What must stay true.** Same facts as the English, nothing added and nothing');
  w('dropped. No emoji, no en or em dash. A body that names a button must use that');
  w("button's Hindi text exactly. A UTILITY template must carry no offer wording at");
  w('all, or Meta reclassifies it as marketing and puts a per-customer cap on the');
  w('order confirmation.');
  w();
  w('Generated by `scripts/dryrun-render.mjs --lang hi`. Do not edit this file by');
  w('hand: it is regenerated, and the registries are the source.');
  w();

  const block = (label, name, body, extra) => {
    w(`**${label}**${name ? ` \`${name}\`` : ''}`);
    w();
    w('```');
    w(body);
    for (const e of extra || []) w(e);
    w('```');
    w();
  };

  w('## Templates');
  w();
  for (const [key, hi] of Object.entries(TEMPLATES_HI)) {
    const en = TEMPLATES[key];
    w(`### ${key}`);
    w();
    w(`${hi.category}${hi.header ? `, ${hi.header.format.toLowerCase()} header` : ''}`
      + `${HI_NOT_SUBMITTED.has(hi.name) ? '. NOT SUBMITTED: needs the review Flow published, like its English twin' : ''}`);
    w();
    block('English', en.name, fillBody(en.body, en.examples), [
      ...(en.footer ? [`(footer) ${en.footer}`] : []),
      ...(en.buttons || []).map((b) => `[${b.kind}] ${b.text}`),
    ]);
    block('Hindi', hi.name, fillBody(hi.body, hi.examples), [
      ...(hi.footer ? [`(footer) ${hi.footer}`] : []),
      ...(hi.buttons || []).map((b) => `[${b.kind}] ${b.text}`),
    ]);
  }

  w('## Templates for when there is no photo or no price to quote');
  w();
  for (const [key, hi] of Object.entries(PLAIN_HI)) {
    const en = NO_PRICE[key] || LEGACY[key];
    w(`### ${key}`);
    w();
    block('English', en.name, fillBody(en.body, en.examples), (en.buttons || []).map((b) => `[${b.kind}] ${b.text}`));
    block('Hindi', hi.name, fillBody(hi.body, hi.examples), (hi.buttons || []).map((b) => `[${b.kind}] ${b.text}`));
  }

  w('## Free-form messages');
  w();
  w('Sent inside the 24 hour window after the customer writes to us or taps a');
  w('button. These need no Meta approval, so a correction here is live on the next');
  w('deploy.');
  w();
  for (const [key, hi] of Object.entries(SESSION_HI)) {
    const en = SESSION[key];
    if (!en) continue;
    w(`### ${key}`);
    w();
    w(`type: ${hi.type}`);
    w();
    const parts = (m) => [
      ...(m.ctaText ? [`[button] ${fillBody(m.ctaText, null)}`] : []),
      ...(m.listButton ? [`[open] ${m.listButton}`] : []),
      ...(m.buttons || []).map((b) => `[reply] ${b.title}`),
    ];
    block('English', '', fillBody(en.body, null), parts(en));
    block('Hindi', '', fillBody(hi.body, null), parts(hi));
  }

  w('## Phrases built in code');
  w();
  w('These are assembled in JavaScript and passed into a message as a variable, so');
  w('they do not appear in any body above. They are the ones most likely to be left');
  w('in English by mistake.');
  w();
  w('| key | English | Hindi |');
  w('| --- | --- | --- |');
  const SAMPLE_ARGS = {
    itemSize: ['M'], itemPieces: [2], itemMore: [1], keepReady: ['Rs 1,499'],
    totalSplit: ['Rs 1,499', 'Rs 500', 'Rs 999'], expiresToday: ['9:20 PM'],
    expiresTomorrow: ['9:20 PM'], expiresOn: ['14 Oct', '9:20 PM'],
    minutesLeft: [50], hoursLeft: [2], hoursMinutesLeft: ['1 hour', 40],
    describeSize: ['XL'], itemQty: ['Noor, size XL', 2],
  };
  const cell = (v) => String(v).replace(/\|/g, '\\|').replace(/\n/g, ' ');
  for (const key of Object.keys(STR.en)) {
    const vals = LANGS.map((l) => {
      const v = STR[l]?.[key] ?? STR.en[key];
      return typeof v === 'function' ? v(...(SAMPLE_ARGS[key] || ['X'])) : v;
    });
    w(`| \`${key}\` | ${cell(vals[0])} | ${cell(vals[1])} |`);
  }
  w();

  mkdirSync('docs', { recursive: true });
  writeFileSync('docs/hindi-copy-review.md', out.join('\n') + '\n');
  console.log(`wrote docs/hindi-copy-review.md (${out.length} lines)`);
  console.log(`${Object.keys(TEMPLATES_HI).length} templates, ${Object.keys(PLAIN_HI).length} plain twins, ${Object.keys(SESSION_HI).length} free-form, ${Object.keys(STR.en).length} fragments`);
  process.exit(0);
}

console.log('=== TEMPLATES ===');
for (const [key, t] of [...Object.entries(TEMPLATES), ...Object.entries(LEGACY)]) {
  const r = renderTemplateDef(t, t.examples, ctx);
  console.log(`\n[${key}] ${r.name} (${t.category})${t.header ? ' [image header]' : ''}`);
  console.log(t.body.replace(/\{\{(\w+)\}\}/g, (_, n) => t.examples[n]));
  if (t.footer) console.log(`(footer) ${t.footer}`);
  for (const b of t.buttons || []) console.log(`  [${b.kind}] ${b.text}`);
}

console.log('\n\n=== SESSION ===');
for (const [key, m] of Object.entries(SESSION)) {
  const names = new Set();
  for (const s of [m.body, m.ctaText || '']) {
    let x;
    const re = /\{\{(\w+)\}\}/g;
    while ((x = re.exec(s))) names.add(x[1]);
  }
  const vars = {};
  for (const n of names) vars[n] = sampleValue(n);
  // A list's rows are per-order, and a button whose action is null carries
  // per-order ids, so both have to be supplied here or renderSession throws.
  // Sample values only; this script renders copy, it never sends.
  const rows =
    m.type === 'list'
      ? [
          { action: 'vcs:1:101', title: 'M' },
          { action: 'vcs:1:102', title: 'L', description: 'in stock' },
        ]
      : undefined;
  const actions = Object.fromEntries(
    (m.buttons || []).filter((b) => !b.action).map((b) => [b.title, 'vcok:1:101']),
  );
  const r = renderSession(key, vars, { ...ctx, rows, actions });
  console.log(`\n[${key}] (${m.type})`);
  console.log(r.body);
  if (r.type === 'list') console.log(`  [open] ${r.buttonText}`);
  else if (r.buttonText) console.log(`  [cta] ${r.buttonText} -> ${r.url}`);
  for (const row of r.rows || []) console.log(`  [row] ${row.title} (${row.id})${row.description ? ` - ${row.description}` : ''}`);
  for (const b of r.buttons || []) console.log(`  [reply] ${b.title} (${b.id})`);
}
console.log('\n\n=== EMAIL (Flow W, for somebody WhatsApp cannot reach) ===');
const mail = renderEmail();
console.log(`\nSubject: ${mail.subject}`);
console.log('\n--- text part ---');
console.log(mail.text);
console.log('\n--- html part, paste it into a browser to look at it ---');
console.log(mail.html);

console.log('\nOK: all copy rendered.');
